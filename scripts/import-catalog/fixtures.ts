// Set one cell of a sheet row (row index 0 = first data row)
export function setCell(
  wb: Workbook,
  sheetName: string,
  rowIndex: number,
  header: string,
  value: CellValue,
): void {
  const row = wb[sheetName]?.rows[rowIndex];
  if (!row) throw new Error(`no row ${rowIndex} in ${sheetName}`);
  row.cells[header] = value;
}
