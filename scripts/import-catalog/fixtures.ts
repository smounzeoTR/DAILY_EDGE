import type { CellValue, Workbook } from './types.ts';

function sheet(headers: string[], rows: CellValue[][]): Workbook[string] {
  return {
    headers,
    rows: rows.map((values, i) => ({
      rowNumber: i + 2,
      cells: Object.fromEntries(headers.map((h, j) => [h, values[j] ?? null])),
    })),
  };
}

